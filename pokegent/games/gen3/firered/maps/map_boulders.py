"""Strength boulders in the map layer: facts, the push rules, the ROM's puzzle data,
``simulate_push``.

Everything here is pure over a :class:`MapState` (no emulator, no RAM write). Sources and evidence:

* **Rules** (decomp ``src/field_player_avatar.c`` ``TryPushBoulder``, implemented by
  :func:`pokegent.games.gen3.firered.maps.map_motion.boulder_push_check`, verified live in
  ``the runtime contracts``
  section 11): a push needs ``FLAG_SYS_USE_STRENGTH`` (0x805), an object with graphics id 97 on
  the tile
  in front of the player, and a far tile that is ``MB_FALL_WARP`` or free (no collision, no
  directional
  wall, no elevation mismatch, no object, not a cave door). The boulder moves exactly one tile
  and the
  PLAYER STAYS on its tile (walk-in-place); the next push needs a step into the vacated tile.
* **Armed** means the flag is set. Every map load clears it (``ClearTempFieldEventData``); it is set
  by a YES to "Would you like to use STRENGTH?" at a boulder (Rainbow badge + a party member that
  knows the move), not by anything in this module.
* **Data** (the local ``boulders.yaml`` cache, generated by the ROM boulder scanner from the ROM
scripts):
  which tile is a switch, which barrier tiles its script opens, which boulders it pins, which
  tiles are
  holes, which barrier tiles ``ON_LOAD`` closes while the puzzle variable is not 100.
* **Despawn hazard**: object events exist only near the camera. A boulder whose current AND template
  tile are outside the view is removed and respawns at its template tile when it comes back, so
  a push
  can be lost when the player walks far away (``RETAIN_*``: measured spawn window dx -11..10, dy
  -7..9
  over 240 spawned objects of the fixture corpus, shrunk by one tile).
"""

from __future__ import annotations

import logging
import os
from collections.abc import Mapping
from dataclasses import dataclass
from functools import lru_cache
from pathlib import Path
from typing import Literal

import yaml

from pokegent.games.gen3.firered.maps import map_constants as K
from pokegent.games.gen3.firered.maps.map_behaviors import behavior_info
from pokegent.games.gen3.firered.maps.map_motion import boulder_push_check
from pokegent.games.gen3.firered.maps.map_schema import (
    Facing,
    MapGrid,
    MapObject,
    MapState,
    PlayerPlacement,
)

_LOG = logging.getLogger(__name__)

PUSHABLE_GFX = K.OBJ_EVENT_GFX_PUSHABLE_BOULDER
STRENGTH_FLAG = K.FLAG_SYS_USE_STRENGTH
PUZZLE_DONE = 100

#: a boulder is only kept alive while the player is inside this box around the boulder's tile
RETAIN_DX = 9
RETAIN_UP = 6
RETAIN_DOWN = 8

PUZZLES_PATH_ENV = "POKEGENT_BOULDER_DATA"


# -- ROM data
# ---------------------------------------------------------------------------------------


@dataclass(frozen=True)
class OpenedTile:
    x: int
    y: int
    metatile: int
    behavior: int | None
    elevation: int | None


@dataclass(frozen=True)
class SwitchData:
    tile: tuple[int, int]
    var: int
    opens: tuple[OpenedTile, ...]
    pins: tuple[int, ...]


@dataclass(frozen=True)
class HoleData:
    tile: tuple[int, int]
    warp: int | None
    to: tuple[int, int, int] | None


@dataclass(frozen=True)
class BoulderTemplate:
    local_id: int
    tile: tuple[int, int]
    elevation: int
    hide_flag: int | None
    reveal_flag: int | None


@dataclass(frozen=True)
class PuzzleData:
    name: str
    group: int
    number: int
    boulders: tuple[BoulderTemplate, ...]
    switches: tuple[SwitchData, ...]
    holes: tuple[HoleData, ...]
    #: ON_LOAD: (puzzle variable, the tiles closed while it is not 100) as (x, y, metatile) triples
    closed: tuple[tuple[int, tuple[tuple[int, int, int], ...]], ...] = ()

    def switch_at(self, xy: tuple[int, int]) -> SwitchData | None:
        return next((s for s in self.switches if s.tile == xy), None)

    def hole_at(self, xy: tuple[int, int]) -> HoleData | None:
        return next((h for h in self.holes if h.tile == xy), None)

    def template(self, local_id: int) -> BoulderTemplate | None:
        return next((b for b in self.boulders if b.local_id == local_id), None)


def default_puzzles_path() -> Path:
    override = os.environ.get(PUZZLES_PATH_ENV)
    if override:
        return Path(override)
    from pokegent.games.gen3.firered.rom.rom_cache import existing_cache_path

    cached = existing_cache_path()
    if cached is not None and (cached / "boulders.yaml").is_file():
        return cached / "boulders.yaml"
    from pokegent.games.gen3.firered.rom.rom_cache import ensure

    if os.environ.get("FIRERED_ROM_PATH"):
        return ensure() / "boulders.yaml"
    from pokegent.games.gen3.firered.rom.rom_cache import RomDataError

    raise RomDataError(
        "ROM-derived boulder data cache is missing; set FIRERED_ROM_PATH and build the cache"
    )


def parse_puzzle_document(doc: object, *, source: str) -> dict[tuple[int, int], PuzzleData]:
    """Decode one already-loaded ``boulders/1`` document with the owner semantics."""
    if not isinstance(doc, Mapping):
        raise ValueError(f"{source}: puzzle document must be a mapping")
    if doc.get("schema") != "boulders/1":
        raise ValueError(f"{source}: unknown schema {doc.get('schema')!r}")
    out: dict[tuple[int, int], PuzzleData] = {}
    for name, m in doc["maps"].items():
        switches = tuple(
            SwitchData(
                tuple(s["tile"]),
                s["trigger_var"],
                tuple(
                    OpenedTile(o["x"], o["y"], o["metatile"], o.get("behavior"), o.get("elevation"))
                    for o in s["opens"]
                ),
                tuple(s["pins"]),
            )
            for s in m["switches"]
        )
        holes = tuple(
            HoleData(tuple(h["tile"]), h["warp"], tuple(h["to"]) if h["to"] else None)
            for h in m["holes"]
        )
        boulders = tuple(
            BoulderTemplate(
                b["local_id"], tuple(b["tile"]), b["elevation"], b["hide_flag"], b["reveal_flag"]
            )
            for b in m["boulders"]
        )
        closed = tuple(
            (c["var"], tuple((t["x"], t["y"], t["metatile"]) for t in c["tiles"]))
            for c in m["closed_until_done"]
        )
        out[(m["group"], m["number"])] = PuzzleData(
            name, m["group"], m["number"], boulders, switches, holes, closed
        )
    return out


def parse_puzzle_bytes(raw: bytes, *, source: str) -> dict[tuple[int, int], PuzzleData]:
    """Decode exact captured puzzle bytes; never re-open ``source``."""
    try:
        doc = yaml.safe_load(raw)
    except yaml.YAMLError as exc:
        raise ValueError(f"{source}: invalid puzzle YAML") from exc
    return parse_puzzle_document(doc, source=source)


@lru_cache(maxsize=4)
def _load(path: str) -> dict[tuple[int, int], PuzzleData]:
    if not Path(path).is_file() and not os.environ.get("FIRERED_ROM_PATH"):
        _LOG.error(
            "ROM-derived boulder data is unavailable at %s; set FIRERED_ROM_PATH and build the cache",  # noqa: E501
            path,
        )
        return {}
    return parse_puzzle_bytes(Path(path).read_bytes(), source=path)


def puzzles(
    path: str | os.PathLike[str] | None = None, *, allow_empty: bool = False
) -> Mapping[tuple[int, int], PuzzleData]:
    """The puzzle data of every map with a boulder, keyed by ``(group, number)``."""
    from pokegent.games.gen3.firered.rom.rom_cache import RomDataError

    try:
        selected = path or default_puzzles_path()
    except RomDataError:
        if allow_empty:
            return {}
        raise
    return _load(str(selected))


def puzzle_for(state: MapState) -> PuzzleData | None:
    return puzzles(allow_empty=True).get((state.identity.group, state.identity.number))


def with_tiles(
    state: MapState, tiles: Mapping[tuple[int, int], tuple[int, int | None]]
) -> MapState:
    """A copy of ``state`` with ``(x, y) -> (metatile, behavior)`` tiles replaced the way the game's
    ``setmetatile`` does: the metatile id and (impassable) the collision bits change, the
    elevation bits
    of the block stay. ``behavior`` (when known) is added to the attribute table."""
    blocks = list(state.grid.blocks)
    attrs = dict(state.grid.attributes)
    cols = state.grid.columns
    for (x, y), (metatile, behavior) in tiles.items():
        index = (y + K.MAP_OFFSET) * cols + x + K.MAP_OFFSET
        elevation = blocks[index] >> K.MAPGRID_ELEVATION_SHIFT
        blocks[index] = metatile | (elevation << K.MAPGRID_ELEVATION_SHIFT)
        if behavior is not None:
            attrs.setdefault(metatile, behavior)
    grid = MapGrid(
        columns=cols, rows=state.grid.rows, blocks=tuple(blocks),
        attributes=tuple(sorted(attrs.items())),
    )  # fmt: skip
    return state.model_copy(update={"grid": grid})


def with_player(
    state: MapState, x: int, y: int, elevation: int = 3, facing: Facing = "N"
) -> MapState:
    """A static map (no player) with a player standing on ``(x, y)``: a what-if state for
    planning."""
    placement = PlayerPlacement(
        save_x=x, save_y=y, avatar_x=x, avatar_y=y, prev_x=x, prev_y=y, x=x, y=y,
        position_consistent=True, facing=facing, elevation=elevation, object_event_id=0,
        avatar_flags=0, surfing=False, underwater=False, biking=False, controllable_flag=True,
        forced=False, moving=False, tile_transition_state=0, running_state=0,
    )  # fmt: skip
    return state.model_copy(update={"player": placement})


_DEFAULT_PUZZLE = object()


def on_load_closed(
    state: MapState, *, puzzle: PuzzleData | None | object = _DEFAULT_PUZZLE
) -> MapState:
    """What the map's ON_LOAD script makes of a static layout while the puzzle variables are
    not 100:
    the barrier tiles show the rock metatiles (775 / 791) with collision 3, as in a fresh visit."""
    data = puzzle_for(state) if puzzle is _DEFAULT_PUZZLE else puzzle
    if data is None or not data.closed:
        return state
    blocks = list(state.grid.blocks)
    cols = state.grid.columns
    tiles = {(x, y): (metatile, None) for _, group in data.closed for x, y, metatile in group}
    closed = with_tiles(state, tiles)
    blocks = list(closed.grid.blocks)
    for x, y in tiles:  # impassable = 1: collision bits set
        blocks[(y + K.MAP_OFFSET) * cols + x + K.MAP_OFFSET] |= K.MAPGRID_COLLISION_MASK
    grid = closed.grid.model_copy(update={"blocks": tuple(blocks)})
    return closed.model_copy(update={"grid": grid})


# -- boulders of a map state
# ------------------------------------------------------------------------


@dataclass(frozen=True)
class Boulder:
    local_id: int
    xy: tuple[int, int]
    elevation: int
    template_xy: tuple[int, int]
    spawned: bool
    hidden: bool  # its hide flag is set: the object does not exist now
    hide_flag: int | None = None
    reveal_flag: int | None = None

    @property
    def displaced(self) -> bool:
        return self.xy != self.template_xy


def boulder_elevation(state: MapState, obj: MapObject) -> int:
    """The elevation the game uses for the object: the live value; an object that is not
    spawned takes
    the elevation of its tile when it spawns (``ObjectEventUpdateElevation``), 0 and 15 keep it."""
    if obj.live is not None:
        return obj.live.elevation
    tile_elevation = state.elevation(obj.x, obj.y)
    return obj.elevation if tile_elevation in (0, 15) else tile_elevation


def boulders(state: MapState) -> tuple[Boulder, ...]:
    """Every boulder object of the map (hidden ones included, flagged), by local id."""
    out = []
    data = puzzle_for(state)
    for obj in sorted(state.objects, key=lambda o: o.local_id):
        if obj.role != "boulder" or obj.graphics_id != PUSHABLE_GFX:
            continue
        template = data.template(obj.local_id) if data else None
        out.append(
            Boulder(
                local_id=obj.local_id,
                xy=(obj.x, obj.y),
                elevation=boulder_elevation(state, obj),
                template_xy=template.tile if template else (obj.x, obj.y),
                spawned=obj.live is not None,
                hidden=obj.hidden_flag_set is True,
                hide_flag=obj.hidden_flag_id or None,
                reveal_flag=template.reveal_flag if template else None,
            )
        )
    return tuple(out)


def armed(state: MapState) -> bool | None:
    """Strength is active for this map load (``FLAG_SYS_USE_STRENGTH``); ``None``: flags
    unreadable."""
    return state.strength_active


def switch_tiles(state: MapState) -> tuple[tuple[int, int], ...]:
    """Tiles with the ``MB_STRENGTH_BUTTON`` behavior (what a boulder must stop on)."""
    return tuple(
        (x, y)
        for y in range(state.layout.height)
        for x in range(state.layout.width)
        if behavior_info(state.behavior(x, y)).kind == "strength_button"
    )


def hole_tiles(state: MapState) -> tuple[tuple[int, int], ...]:
    """Tiles with the ``MB_FALL_WARP`` behavior (a boulder pushed there falls to the floor
    below)."""
    fall = K.MB["MB_FALL_WARP"]
    return tuple(
        (x, y)
        for y in range(state.layout.height)
        for x in range(state.layout.width)
        if state.behavior(x, y) == fall
    )


def retained(player_xy: tuple[int, int], boulder_xy: tuple[int, int]) -> bool:
    """Whether a boulder at ``boulder_xy`` is certainly still spawned with the player at
    ``player_xy``."""
    dx, dy = player_xy[0] - boulder_xy[0], player_xy[1] - boulder_xy[1]
    return abs(dx) <= RETAIN_DX and -RETAIN_DOWN <= dy <= RETAIN_UP


# -- simulate_push
# ----------------------------------------------------------------------------------

PushOutcome = Literal["moves", "falls", "blocked", "unarmed", "missing"]


@dataclass(frozen=True)
class PushResult:
    """What pushing boulder ``boulder`` toward ``direction`` does, per the game's rules.

    ``moves``: it rolls one tile (``to_xy``), the player stays on ``stand_xy``; ``falls``:
    ``to_xy`` is
    a hole and the boulder disappears; ``blocked``: ``reason`` says what is in the way; ``unarmed``:
    Strength is not active (the flag is clear); ``missing``: no such boulder, or it is hidden.
    ``switch`` is the switch data when the boulder stops on a ``MB_STRENGTH_BUTTON`` tile that
    the ROM
    data knows (``lands_on_switch`` is true for the behavior alone).
    """

    boulder: int
    direction: Facing
    outcome: PushOutcome
    reason: str | None
    from_xy: tuple[int, int]
    to_xy: tuple[int, int]
    stand_xy: tuple[int, int]
    lands_on_switch: bool = False
    switch: SwitchData | None = None
    hole: HoleData | None = None

    @property
    def legal(self) -> bool:
        return self.outcome in ("moves", "falls")


def simulate_push(
    state: MapState,
    local_id: int,
    direction: Facing,
    *,
    armed_override: bool | None = None,
) -> PushResult:
    """Pure model of one push; ``armed_override`` replaces ``state.strength_active`` (None: use it).

    The player is assumed to stand behind the boulder facing ``direction`` (``stand_xy``);
    whether the
    player can actually get there is the navigator's question, not this function's.
    """
    vx, vy = K.VECTOR[direction]
    obj = state.object_by_local_id(local_id)
    if obj is None or obj.role != "boulder" or obj.graphics_id != PUSHABLE_GFX:
        return PushResult(local_id, direction, "missing", "no_such_boulder", (0, 0), (0, 0), (0, 0))
    here = (obj.x, obj.y)
    stand = (here[0] - vx, here[1] - vy)
    to = (here[0] + vx, here[1] + vy)
    if obj.hidden_flag_set is True:
        return PushResult(local_id, direction, "missing", "hidden", here, to, stand)
    on = state.strength_active if armed_override is None else armed_override
    if not on:
        return PushResult(local_id, direction, "unarmed", "strength_not_active", here, to, stand)
    outcome, reason = boulder_push_check(
        state, here[0], here[1], boulder_elevation(state, obj), direction, skip=obj.live
    )
    if outcome == "blocked":
        return PushResult(local_id, direction, "blocked", reason, here, to, stand)
    data = puzzle_for(state)
    if outcome == "falls":
        return PushResult(
            local_id, direction, "falls", None, here, to, stand,
            hole=data.hole_at(to) if data else None,
        )  # fmt: skip
    button = behavior_info(state.behavior(*to)).kind == "strength_button"
    return PushResult(
        local_id, direction, "moves", None, here, to, stand,
        lands_on_switch=button, switch=data.switch_at(to) if data else None,
    )  # fmt: skip
